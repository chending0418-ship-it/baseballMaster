package cc.baseballmaster.core

import java.io.File
import kotlinx.serialization.json.*
import org.junit.Assert.*
import org.junit.Test

/** Actual current Kotlin outputs for the separate Swift decoder check; never overwrite references. */
class AppleWireFixtureExportTest {
    private val root = File(System.getProperty("parity.fixtures"), "backup")
    private val output = File(System.getProperty("wire.output"))
    private fun load(name: String) = AppleBackupEnvelope.inspect(File(root, name).readBytes()).snapshot.getValue("games").jsonArray.single().jsonObject
    private fun save(name: String, bytes: ByteArray) { output.mkdirs(); File(output, name).writeBytes(bytes) }

    @Test fun exportsNativeCorrectedHistoryWithLaterPitchAndRevertAudit() {
        var game = AppleReplayPrototype.replay(load("android-game-prototype-v7.bmbackup"))
        // Input was generated by the Android engine, not an imported iOS game.
        game = MatchEngine.correct(game, 1, Command("play", outcome = Outcome.error, fielding = Fielding(errorPosition = 6)), "安打应为游击失误")
        game = MatchEngine.apply(game, Command("pitch", pitch = PitchAction.ball, at = 1_800_000_000_000), "d4000000-0000-0000-0000-000000000001")
        val bytes = AppleExportPrototype.encode(game)
        val stored = AppleBackupEnvelope.inspect(bytes).snapshot.getValue("games").jsonArray.single().jsonObject
        val state = stored.getValue("state").jsonObject
        val revision = state.getValue("correctionRevisions").jsonArray.single().jsonObject
        assertEquals(game.historyRevisions.single().id.uppercase(), revision.getValue("id").jsonPrimitive.content)
        assertEquals(game.historyRevisions.single().appliedOperationIDs.map { it.uppercase() }.toSet(), revision.getValue("appliedOperationIDs").jsonArray.map { it.jsonPrimitive.content }.toSet())
        assertTrue(state.getValue("statisticsIncomplete").jsonPrimitive.boolean)
        assertTrue(state.getValue("scoringEvents").jsonArray.any { it.jsonObject.getValue("needsReview").jsonPrimitive.boolean })
        assertEquals(1, state.getValue("plateAppearancePitchCount").jsonPrimitive.int)
        val replayed = AppleReplayPrototype.replay(stored)
        assertEquals(game.batting, replayed.batting); assertEquals(game.fielding, replayed.fielding)
        assertEquals(game.pitching, replayed.pitching); assertTrue(replayed.statisticsIncomplete)
        val reverted = History.preview(replayed, History.revertingDraft(replayed))
        assertTrue(reverted.conflict, reverted.canSave)
        assertEquals(1, reverted.game!!.awayHits); assertEquals(1, reverted.game!!.balls)
        save("native-corrected.bmbackup", bytes)
        // Export the committed revert as a second audit entry, including the new later pitch.
        val revertedGame = History.commit(replayed, History.revertingDraft(replayed))
        val reverse = AppleExportPrototype.encode(revertedGame)
        assertEquals(2, AppleBackupEnvelope.inspect(reverse).snapshot.getValue("games").jsonArray.single().jsonObject.getValue("state").jsonObject.getValue("correctionRevisions").jsonArray.size)
        save("native-reverted.bmbackup", reverse)
    }

    @Test fun exportsSubstitutionsWithHistoricalBatterChainFieldingAndRunnerOwnership() {
        fun team(prefix: String, opponent: Boolean) = Team("$prefix-0000-0000-0000-000000000000", "合成换人队$prefix",
            (1..12).map { n -> Player("$prefix-0000-0000-0000-${n.toString().padStart(12, '0')}", "球员$n", n.toString(), position = if (n <= 9) n else 1) }, isOpponent = opponent)
        val away = team("a5000000", false); val home = team("b5000000", true)
        val time = 1_790_000_000_000L
        var game = MatchFactory.create("c5000000-0000-0000-0000-000000000000", home, away, Rules(), away.id).copy(createdAt = time, updatedAt = time)
        var n = 0
        fun apply(command: Command) { n++; game = MatchEngine.apply(game, command.copy(at = time + n * 1000), "d5000000-0000-0000-0000-${n.toString().padStart(12, '0')}") }
        apply(Command("pitch", pitch = PitchAction.calledStrike))
        apply(Command("batter", playerID = away.players[9].id))
        apply(Command("pitch", pitch = PitchAction.ball))
        apply(Command("play", outcome = Outcome.single))
        apply(Command("pinchRunner", position = 1, playerID = away.players[10].id))
        apply(Command("pitcher", playerID = home.players[9].id))
        apply(Command("position", playerID = home.players[1].id, position = 6))
        apply(Command("fielder", playerID = home.players[6].id, replacementID = home.players[10].id))
        apply(Command("play", outcome = Outcome.groundOut, observation = Observation(type = "ground", precision = "point", x = .4, y = .6, fielding = Fielding(route = listOf(6, 3)))))
        val bytes = AppleExportPrototype.encode(game)
        val stored = AppleBackupEnvelope.inspect(bytes).snapshot.getValue("games").jsonArray.single().jsonObject
        val state = stored.getValue("state").jsonObject
        val first = state.getValue("plateAppearances").jsonArray.first().jsonObject
        assertEquals(listOf(away.players[0].id.uppercase(), away.players[9].id.uppercase()), first.getValue("batterIDs").jsonArray.map { it.jsonPrimitive.content })
        val replay = AppleReplayPrototype.replay(stored)
        assertEquals(game.homePositions, replay.homePositions); assertEquals(game.awayPositions, replay.awayPositions)
        assertEquals(game.homeOrder, replay.homeOrder); assertEquals(game.awayOrder, replay.awayOrder)
        assertEquals(game.exitedPlayers, replay.exitedPlayers); assertEquals(game.bases, replay.bases)
        assertEquals(game.runnerPitcherIDs, replay.runnerPitcherIDs)
        assertEquals(home.players[0].id, replay.runnerPitcherIDs[away.players[10].id])
        val route = state.getValue("scoringEvents").jsonArray.last().jsonObject.getValue("battedBall").jsonObject.getValue("fielding").jsonObject.getValue("participants").jsonArray
        assertEquals(home.players[1].id.uppercase(), route.single { it.jsonObject.getValue("position").jsonPrimitive.int == 6 }.jsonObject.getValue("playerID").jsonPrimitive.content)
        save("native-substitutions.bmbackup", bytes)
    }

    @Test fun exportsCurrentPitchCountAndOriginalIOSContinuationForSwiftModels() {
        var native = AppleReplayPrototype.replay(load("android-game-prototype-v7.bmbackup"))
        native = MatchEngine.apply(native, Command("pitch", pitch = PitchAction.calledStrike, at = 1_800_000_000_000), "d4000000-0000-0000-0000-000000000002")
        val bytes = AppleExportPrototype.encode(native)
        val state = AppleBackupEnvelope.inspect(bytes).snapshot.getValue("games").jsonArray.single().jsonObject.getValue("state").jsonObject
        assertEquals(1, state.getValue("plateAppearancePitchCount").jsonPrimitive.int)
        save("native-current-appearance.bmbackup", bytes)
        val source = File(root, "ios-correction-reference.bmbackup").readBytes()
        val id = AppleBackupEnvelope.inspect(source).snapshot.getValue("games").jsonArray.single().jsonObject.getValue("id").jsonPrimitive.content
        val continued = AppleGameContinuation.create(source, id).appendNonterminalPitch(PitchAction.calledStrike, "d4000000-0000-0000-0000-000000000003", 1_800_000_000_000)
        save("ios-corrected-continued.bmbackup", continued.exportBackup())
    }
}
