#!/usr/bin/env python3
"""Run the assigned scorer and lineup editor on separate iOS simulators against an in-memory service."""
import argparse
import json
from pathlib import Path
import plistlib
import secrets
import subprocess
import tempfile
from urllib.request import Request, urlopen
from uuid import uuid4


def fixture(port):
    def post(key, path, values):
        request = Request(f"http://127.0.0.1:{port}/api/v3/{path}", data=json.dumps(values).encode(),
                          headers={"Content-Type": "application/json", "X-BM-Protocol": "1",
                                   "Authorization": f"Bearer {key}"})
        with urlopen(request, timeout=10) as response:
            return json.load(response)

    admin, scorer, token = [secrets.token_urlsafe(32) for _ in range(3)]
    for key in (admin, scorer):
        post(key, "devices", {"label": "3.1.4 模拟器"})
    team = post(admin, "teams", {"operationID": str(uuid4()), "name": "双机验收队", "nickname": "阵容员"})
    post(admin, f"teams/{team['teamID']}/invitations",
         {"operationID": str(uuid4()), "token": token, "role": "scorer"})
    partner = post(scorer, "invitations/redeem",
                   {"operationID": str(uuid4()), "token": token, "nickname": "局面员"})
    return admin, scorer, {"BM314_PORT": str(port), "BM314_TEAM": team["teamID"], "BM314_PARTNER": partner["memberID"]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("xctestrun", type=Path, help="iOS simulator manifest generated by xcodebuild build-for-testing")
    parser.add_argument("lineup_simulator")
    parser.add_argument("scoring_simulator")
    args = parser.parse_args()
    if args.lineup_simulator == args.scoring_simulator:
        parser.error("Two different simulator IDs are required.")
    repo = Path(__file__).resolve().parents[2]
    manifest = args.xctestrun.resolve(strict=True)
    results = repo / "output/validation/314" / f"two-devices-{uuid4().hex[:8]}"
    results.mkdir(parents=True)
    js = """import {createCollaborationServer} from './collaboration/server.mjs';
const app = createCollaborationServer({requestsPerMinute:2000});
app.server.listen(0,'127.0.0.1',() => console.log(app.server.address().port));"""
    service = subprocess.Popen(["node", "--input-type=module", "-e", js], cwd=repo,
                               stdout=subprocess.PIPE, text=True)
    children, temporary = [], []
    try:
        admin, scorer, settings = fixture(int(service.stdout.readline()))
        for role, simulator, credential in [("lineup", args.lineup_simulator, admin),
                                             ("scorer", args.scoring_simulator, scorer)]:
            with manifest.open("rb") as stream:
                data = plistlib.load(stream)
            targets = [target for configuration in data.get("TestConfigurations", [])
                       for target in configuration["TestTargets"]] or list(data.values())
            target = next(target for target in targets if target.get("BlueprintName") == "BaseballMasterTests")
            target.setdefault("EnvironmentVariables", {}).update(settings, BM314_DEVICE=credential)
            # Keeping the temporary manifest next to the original preserves __TESTROOT__ expansion.
            with tempfile.NamedTemporaryFile(dir=manifest.parent, suffix=".xctestrun", delete=False) as stream:
                temporary.append(Path(stream.name))
                plistlib.dump(data, stream)
            cmd = ["xcodebuild", "test-without-building", "-xctestrun", stream.name,
                   "-destination", f"platform=iOS Simulator,id={simulator}", "-parallel-testing-enabled", "NO",
                   "-only-testing:BaseballMasterTests/GameStoreTests/testV314LiveScoringOnTwoSimulators",
                   "-resultBundlePath", str(results / (role + ".xcresult"))]
            with (results / (role + ".log")).open("w") as log:
                children.append(subprocess.Popen(cmd, cwd=repo, stdout=log, stderr=subprocess.STDOUT))
        codes = [child.wait(timeout=240) for child in children]
        print(results)
        for role, code in zip(("lineup", "scorer"), codes):
            log = (results / (role + ".log")).read_text()
            if code or "testV314LiveScoringOnTwoSimulators]' passed" not in log:
                raise SystemExit(f"{role} did not pass; see {role}.log")
    finally:
        for child in children:
            if child.poll() is None:
                child.terminate()
                child.wait()
        service.terminate()
        service.wait()
        for path in temporary:
            path.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
